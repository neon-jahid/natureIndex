export type Lang = 'en' | 'bn';

/** A string available in both languages. */
export interface LocalizedText {
  en: string;
  bn: string;
}

/** A list of strings available in both languages (same length & order in both). */
export interface LocalizedList {
  en: string[];
  bn: string[];
}

export type CategoryId =
  | 'mammals'
  | 'birds'
  | 'reptiles'
  | 'amphibians'
  | 'fish'
  | 'insects'
  | 'plants'
  | 'trees'
  | 'flowers'
  | 'fungi'
  | 'marine'
  | 'freshwater';

export type HabitatId =
  | 'tropical-forest'
  | 'temperate-forest'
  | 'mangrove'
  | 'grassland'
  | 'wetland'
  | 'rivers-lakes'
  | 'ocean'
  | 'coral-reef'
  | 'desert'
  | 'mountain'
  | 'polar'
  | 'urban-farmland';

export type RegionId =
  | 'south-asia'
  | 'southeast-asia'
  | 'east-asia'
  | 'africa'
  | 'europe'
  | 'north-america'
  | 'south-america'
  | 'oceania'
  | 'polar'
  | 'oceans';

/** IUCN Red List categories. NE = Not Evaluated, DD = Data Deficient. */
export type IUCNStatus = 'EX' | 'EW' | 'CR' | 'EN' | 'VU' | 'NT' | 'LC' | 'DD' | 'NE';

export type PopulationTrend = 'increasing' | 'decreasing' | 'stable' | 'unknown';

/** [latitude, longitude] */
export type LatLng = [number, number];

export interface Species {
  id: string;
  commonName: LocalizedText;
  scientificName: string;
  /** Other names used for search: alternative English/Bengali common names. */
  altNames: LocalizedList;
  /** Scientific synonyms (Latin). */
  synonyms?: string[];
  category: CategoryId;
  /** Extra categories the species also belongs to (e.g. a marine fish → ['marine']). */
  secondaryCategories?: CategoryId[];
  /** Exact English Wikipedia article title, used to source photographs. */
  wikiTitle: string;
  description: LocalizedText;
  taxonomy: {
    kingdom: string;
    phylum: string;
    class: string;
    order: string;
    family: string;
    genus: string;
    species: string;
  };
  physical: {
    size: LocalizedText;
    weight: LocalizedText;
    lifespan: LocalizedText;
    features: LocalizedList;
  };
  habitat: LocalizedText;
  habitats: HabitatId[];
  regions: RegionId[];
  distribution: LocalizedText;
  climate: LocalizedText;
  diet: LocalizedText;
  ecologicalRole: LocalizedText;
  behavior: LocalizedText;
  range: {
    /** Representative points inside the native range (3–8 points). */
    native: LatLng[];
    /** Representative points where the species has been introduced by humans. */
    introduced?: LatLng[];
    /** Present only when the species is endemic to a specific region. */
    endemicTo?: LocalizedText;
  };
  conservation: {
    status: IUCNStatus;
    trend: PopulationTrend;
    /** Estimated wild population, if reliably known. */
    population?: LocalizedText;
    threats: LocalizedList;
    initiatives: LocalizedList;
    /** Year (YYYY) of the latest IUCN assessment, when known. */
    assessed?: string;
  };
  facts: LocalizedList;
  related: string[];
}

/**
 * Lightweight record kept in the main bundle (generated by scripts/build-index.mjs).
 * Used for search, cards, maps and charts; the full `Species` is lazy-loaded.
 */
export type SpeciesSummary = Pick<
  Species,
  | 'id'
  | 'commonName'
  | 'scientificName'
  | 'altNames'
  | 'synonyms'
  | 'category'
  | 'secondaryCategories'
  | 'wikiTitle'
  | 'taxonomy'
  | 'habitat'
  | 'habitats'
  | 'regions'
  | 'range'
  | 'related'
> & {
  /** Data file (without extension) holding the full record. */
  file: string;
  conservation: Pick<Species['conservation'], 'status' | 'trend' | 'population' | 'assessed'>;
};

/* Names & descriptions of categories, habitats and regions live in the
   `categories` translation namespace (src/i18n/locales/{en,bn}/categories.json). */

export interface Category {
  id: CategoryId;
  icon: string;
  wikiTitle: string;
  /** Tailwind gradient classes for the card accent. */
  gradient: string;
}

export interface Habitat {
  id: HabitatId;
  icon: string;
  wikiTitle: string;
  center: LatLng;
  gradient: string;
}

export interface Region {
  id: RegionId;
  center: LatLng;
}
